/** Pharmacy PC agent: tick script + continuous pull loop. Platform/token baked in Node. */

function tickScriptSource(platform: string, token: string): string {
  return [
    "$ErrorActionPreference = 'Continue'",
    "[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12",
    `$Platform = '${platform.replace(/'/g, "''")}'`,
    `$EmbeddedToken = '${token.replace(/'/g, "''")}'`,
    "$Port = @@AGENT_PORT@@",
    "$InstallDir = Join-Path $env:ProgramData 'PHARMXS'",
    "$TokenFile = Join-Path $InstallDir 'agent.token'",
    "$LogPath = Join-Path $InstallDir 'agent.log'",
    "",
    "function Get-AgentToken {",
    "  try {",
    "    if (Test-Path $TokenFile) {",
    "      $t = ([string](Get-Content -Path $TokenFile -Raw -ErrorAction SilentlyContinue)).Trim()",
    "      if ($t.Length -gt 8) { return $t }",
    "    }",
    "  } catch {}",
    "  return $EmbeddedToken",
    "}",
    "",
    "function Write-AgentLog([string]$m) {",
    "  try {",
    "    if (-not (Test-Path $InstallDir)) { New-Item -ItemType Directory -Force -Path $InstallDir | Out-Null }",
    "    Add-Content -Path $LogPath -Value ('[' + (Get-Date -Format 'yyyy-MM-dd HH:mm:ss') + '] ' + $m) -Encoding UTF8 -ErrorAction SilentlyContinue",
    "  } catch {}",
    "}",
    "",
    "function Send-Hello {",
    "  $Token = Get-AgentToken",
    "  $ips = @(); try { $ips = @(Get-NetIPAddress -AddressFamily IPv4 -EA SilentlyContinue | Where-Object { $_.IPAddress -notlike '127.*' } | Select-Object -ExpandProperty IPAddress -Unique) } catch {}",
    "  $pub = $null; try { $pub = (Invoke-RestMethod -Uri 'https://api.ipify.org?format=json' -TimeoutSec 8).ip } catch {}",
    "  if (-not $pub -and $ips.Count -gt 0) { $pub = $ips[0] }",
    "  $listening = $false; try { $listening = [bool](Get-NetTCPConnection -State Listen -LocalPort $Port -EA SilentlyContinue) } catch {}",
    "  $payload = (@{ token=$Token; host=$pub; port=$Port; machine=$env:COMPUTERNAME; localIps=$ips; reportListening=$listening; protocol='http' } | ConvertTo-Json -Compress)",
    "  Invoke-RestMethod -Method Post -Uri ($Platform + '/api/fom/agent/hello') -ContentType 'application/json; charset=utf-8' -Body $payload -TimeoutSec 45 | Out-Null",
    "  Write-AgentLog ('hello ok listening=' + $listening)",
    "}",
    "",
    "function Invoke-JobPoll {",
    "  $Token = Get-AgentToken",
    "  $poll = Invoke-RestMethod -Method Post -Uri ($Platform + '/api/fom/agent/poll') -ContentType 'application/json; charset=utf-8' -Body ((@{ token = $Token } | ConvertTo-Json -Compress)) -TimeoutSec 30",
    "  $jobs = @(); if ($null -ne $poll.jobs) { $jobs = @($poll.jobs) }",
    "  Write-AgentLog ('poll ok jobs=' + $jobs.Count)",
    "  foreach ($job in $jobs) {",
    "    try {",
    "      Write-AgentLog ('fetch ' + $job.localUrl)",
    "      $resp = Invoke-WebRequest -Uri $job.localUrl -UseBasicParsing -TimeoutSec 900",
    "      $xml = [string]$resp.Content",
    "      if ($xml -match '(?i)<HTML|<BODY>\\s*<B>\\s*200') { throw 'REPORT HTML 200 OK' }",
    "      $b64 = [Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes($xml))",
    "      $result = (@{ token=$Token; jobId=$job.id; ok=$true; xmlBase64=$b64 } | ConvertTo-Json -Compress -Depth 4)",
    "      Invoke-RestMethod -Method Post -Uri ($Platform + '/api/fom/agent/job-result') -ContentType 'application/json; charset=utf-8' -Body $result -TimeoutSec 900 | Out-Null",
    "      Write-AgentLog ('job ok ' + $job.id + ' bytes=' + $xml.Length)",
    "    } catch {",
    "      $msg = [string]$_.Exception.Message",
    "      Write-AgentLog ('job fail ' + $job.id + ' ' + $msg)",
    "      try { Invoke-RestMethod -Method Post -Uri ($Platform + '/api/fom/agent/job-result') -ContentType 'application/json; charset=utf-8' -Body ((@{ token=$Token; jobId=$job.id; ok=$false; message=$msg } | ConvertTo-Json -Compress)) -TimeoutSec 30 | Out-Null } catch {}",
    "    }",
    "  }",
    "  return $jobs.Count",
    "}",
    "",
    "New-Item -ItemType Directory -Force -Path $InstallDir | Out-Null",
    "Write-AgentLog ('tick pid=' + $PID + ' port=' + $Port)",
    "try { Send-Hello } catch { Write-AgentLog ('hello fail ' + $_.Exception.Message) }",
    "$deadline = (Get-Date).AddSeconds(55)",
    "while ((Get-Date) -lt $deadline) {",
    "  $n = 0",
    "  try { $n = Invoke-JobPoll } catch { Write-AgentLog ('poll fail ' + $_.Exception.Message); break }",
    "  if ($n -lt 1) { break }",
    "  Start-Sleep -Milliseconds 150",
    "}",
    "Write-AgentLog 'tick end'",
  ].join("\n");
}

export function fomAgentInstallScriptTemplate(opts: { platform: string; token: string }): string {
  const workerB64 = Buffer.from(tickScriptSource(opts.platform, opts.token), "utf8").toString("base64");

  return [
    "# PHARMXS FOM - FOM bazasini platformaga tortish",
    "$ErrorActionPreference = 'Stop'",
    "[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12",
    "$Platform = '__PLATFORM__'",
    "$Token = '__TOKEN__'",
    "$PreferredPort = __PORT__",
    "$TaskName = 'PHARMXS-FOM-Agent'",
    "$InstallDir = Join-Path $env:ProgramData 'PHARMXS'",
    "$WorkerPath = Join-Path $InstallDir 'fom-agent-worker.ps1'",
    "$LogPath = Join-Path $InstallDir 'agent.log'",
    "$WorkerB64 = '" + workerB64 + "'",
    "",
    "function Write-Ok([string]$m){ Write-Host ('[OK] ' + $m) -ForegroundColor Green }",
    "function Write-Warn([string]$m){ Write-Host ('[!] ' + $m) -ForegroundColor Yellow }",
    "function Write-Err([string]$m){ Write-Host ('[X] ' + $m) -ForegroundColor Red }",
    "",
    "$isAdmin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)",
    "if (-not $isAdmin) { Write-Err 'Admin sifatida oching.'; exit 1 }",
    "",
    "Write-Host ''",
    "Write-Host '=== PHARMXS ulanish ===' -ForegroundColor Cyan",
    "Write-Host '01.01.2025 dan bugungacha tortiladi, keyin avtomatik yangilanadi.'",
    "Write-Host ('Platforma: ' + $Platform)",
    "Write-Host ('Kompyuter: ' + $env:COMPUTERNAME)",
    "Write-Host ''",
    "",
    "Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false -ErrorAction SilentlyContinue",
    "Unregister-ScheduledTask -TaskName 'PHARMXS-FOM-AgentWatch' -Confirm:$false -ErrorAction SilentlyContinue",
    "Get-CimInstance Win32_Process -EA SilentlyContinue |",
    "  Where-Object { $_.CommandLine -and ($_.CommandLine -like '*fom-agent-worker*' -or $_.CommandLine -like '*fom-agent-watch*') } |",
    "  ForEach-Object { try { Stop-Process -Id $_.ProcessId -Force -EA SilentlyContinue } catch {} }",
    "",
    "$listenPorts = @()",
    "try { $listenPorts = @(Get-NetTCPConnection -State Listen -EA SilentlyContinue | Where-Object { $_.LocalPort -ge 1024 } | Select-Object -ExpandProperty LocalPort -Unique) } catch {}",
    "$port = $PreferredPort",
    "if ($listenPorts -contains $PreferredPort) { Write-Ok ('REPORT: ' + $port) }",
    "elseif ($listenPorts.Count -gt 0) {",
    "  foreach ($cand in (@(8084,8080,8085,8090,8081,8082) + $listenPorts)) { if ($listenPorts -contains $cand) { $port = $cand; break } }",
    "  Write-Warn ('Port: ' + $port)",
    "} else { Write-Warn ('8084 tinglanmayapti - REPORT.exe ni yoqing') }",
    "",
    "$ruleName = ('PHARMXS FOM REPORT TCP ' + $port)",
    "Get-NetFirewallRule -DisplayName $ruleName -EA SilentlyContinue | Remove-NetFirewallRule -EA SilentlyContinue",
    "New-NetFirewallRule -DisplayName $ruleName -Direction Inbound -Action Allow -Protocol TCP -LocalPort $port -Profile Any | Out-Null",
    "Write-Ok ('Firewall TCP ' + $port)",
    "",
    "$localIps = @(); try { $localIps = @(Get-NetIPAddress -AddressFamily IPv4 -EA SilentlyContinue | Where-Object { $_.IPAddress -notlike '127.*' -and $_.PrefixOrigin -ne 'WellKnown' } | Select-Object -ExpandProperty IPAddress -Unique) } catch {}",
    "$publicIp = $null; try { $publicIp = (Invoke-RestMethod -Uri 'https://api.ipify.org?format=json' -TimeoutSec 12).ip } catch {}",
    "if (-not $publicIp -and $localIps.Count -gt 0) { $publicIp = $localIps[0] }",
    "if ($publicIp) { Write-Host ('IP: ' + $publicIp) }",
    "$reportListening = $listenPorts -contains $port",
    "",
    "New-Item -ItemType Directory -Force -Path $InstallDir | Out-Null",
    "$tickText = [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($WorkerB64)).Replace('@@AGENT_PORT@@', [string]$port)",
    "$utf8 = New-Object System.Text.UTF8Encoding $true",
    "[IO.File]::WriteAllText($WorkerPath, $tickText, $utf8)",
    "[IO.File]::WriteAllText((Join-Path $InstallDir 'agent.token'), $Token, $utf8)",
    "Write-Ok ('Agent: ' + $WorkerPath)",
    "",
    "# Task as CURRENT USER (SYSTEM often cannot HTTPS) - every 1 min",
    "$taskArgs = '-NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File \"' + $WorkerPath + '\"'",
    "$action = New-ScheduledTaskAction -Execute 'powershell.exe' -Argument $taskArgs",
    "$trigger = New-ScheduledTaskTrigger -Once -At (Get-Date).AddSeconds(15) -RepetitionInterval (New-TimeSpan -Minutes 1) -RepetitionDuration (New-TimeSpan -Days 3650)",
    "$principal = New-ScheduledTaskPrincipal -UserId $env:USERNAME -LogonType Interactive -RunLevel Highest",
    "$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable -MultipleInstances IgnoreNew -ExecutionTimeLimit (New-TimeSpan -Minutes 30)",
    "try {",
    "  Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger -Principal $principal -Settings $settings | Out-Null",
    "  Write-Ok ('Task (user ' + $env:USERNAME + '): har 1 daqiqa')",
    "} catch {",
    "  Write-Warn ('Task: ' + $_.Exception.Message)",
    "}",
    "",
    "$body = (@{ token=$Token; host=$publicIp; port=$port; machine=$env:COMPUTERNAME; localIps=$localIps; reportListening=[bool]$reportListening; protocol='http' } | ConvertTo-Json -Compress)",
    "try { $res = Invoke-RestMethod -Method Post -Uri ($Platform + '/api/fom/agent/hello') -ContentType 'application/json; charset=utf-8' -Body $body -TimeoutSec 60 }",
    "catch { Write-Err ('Ulanish xato: ' + $_.Exception.Message); exit 1 }",
    "if (-not $res.ok) { Write-Err ([string]$res.message); exit 1 }",
    "Write-Ok ([string]$res.message)",
    "",
    "try {",
    "  $syncRes = Invoke-RestMethod -Method Post -Uri ($Platform + '/api/fom/agent/start-sync') -ContentType 'application/json; charset=utf-8' -Body ((@{ token = $Token } | ConvertTo-Json -Compress)) -TimeoutSec 60",
    "  Write-Ok ('Sync: ' + [string]$syncRes.message)",
    "} catch { Write-Warn ('Sync: ' + $_.Exception.Message) }",
    "",
    "Write-Host ''",
    "Write-Host 'ULANDI. Malumot tortilmoqda. Oynani yopish mumkin - har 1 daqiqada davom etadi.' -ForegroundColor Green",
    "Write-Host 'Tezroq tortish uchun oynani ochiq qoldiring (Ctrl+C = faqat shu oynani toxtatadi).' -ForegroundColor Yellow",
    "Write-Host ('Log: ' + $LogPath)",
    "Write-Host ''",
    "$n = 0",
    "while ($true) {",
    "  $n++",
    "  try {",
    "    & powershell.exe -NoProfile -ExecutionPolicy Bypass -File $WorkerPath",
    "    if ($n -eq 1) { Write-Ok 'Poll ishlayapti - FOM bazasi platformaga ketmoqda' }",
    "    elseif (($n % 10) -eq 0) { Write-Host (('[' + (Get-Date -Format 'HH:mm:ss') + '] tick #' + $n)) -ForegroundColor DarkGray }",
    "  } catch { Write-Warn $_.Exception.Message }",
    "  if (Test-Path $LogPath) {",
    "    $hit = @(Get-Content $LogPath -Tail 6 -EA SilentlyContinue | Where-Object { $_ -match 'job ok' })",
    "    if ($hit.Count -gt 0) { Write-Ok $hit[-1] }",
    "  }",
    "  Start-Sleep -Milliseconds 800",
    "}",
  ].join("\n");
}
