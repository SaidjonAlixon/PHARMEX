/** Install script for pharmacy PCs. Worker is embedded as base64 to avoid quote bugs. */

function workerScriptSource(): string {
  return [
    "$ErrorActionPreference = 'Continue'",
    "$Platform = '__PLATFORM__'",
    "$Token = '__TOKEN__'",
    "$Port = __PORT__",
    "$lastHello = [DateTime]::MinValue",
    "",
    "function Send-Hello {",
    "  $ips = @()",
    "  try {",
    "    $ips = @(Get-NetIPAddress -AddressFamily IPv4 -ErrorAction SilentlyContinue |",
    "      Where-Object { $_.IPAddress -notlike '127.*' } |",
    "      Select-Object -ExpandProperty IPAddress -Unique)",
    "  } catch {}",
    "  $pub = $null",
    "  try { $pub = (Invoke-RestMethod -Uri 'https://api.ipify.org?format=json' -TimeoutSec 8).ip } catch {}",
    "  if (-not $pub -and $ips.Count -gt 0) { $pub = $ips[0] }",
    "  $listening = $false",
    "  try { $listening = [bool](Get-NetTCPConnection -State Listen -LocalPort $Port -ErrorAction SilentlyContinue) } catch {}",
    "  $payload = (@{",
    "    token = $Token",
    "    host = $pub",
    "    port = $Port",
    "    machine = $env:COMPUTERNAME",
    "    localIps = $ips",
    "    reportListening = $listening",
    "    protocol = 'http'",
    "  } | ConvertTo-Json -Compress)",
    "  Invoke-RestMethod -Method Post -Uri ($Platform + '/api/fom/agent/hello') -ContentType 'application/json; charset=utf-8' -Body $payload -TimeoutSec 45 | Out-Null",
    "}",
    "",
    "function Invoke-JobPoll {",
    "  $pollBody = (@{ token = $Token } | ConvertTo-Json -Compress)",
    "  $poll = Invoke-RestMethod -Method Post -Uri ($Platform + '/api/fom/agent/poll') -ContentType 'application/json; charset=utf-8' -Body $pollBody -TimeoutSec 30",
    "  $jobs = @($poll.jobs)",
    "  if ($jobs.Count -lt 1) { return 2 }",
    "  foreach ($job in $jobs) {",
    "    try {",
    "      $resp = Invoke-WebRequest -Uri $job.localUrl -UseBasicParsing -TimeoutSec 180",
    "      $xml = [string]$resp.Content",
    "      $resultObj = @{ token = $Token; jobId = $job.id; ok = $true; xml = $xml }",
    "      $result = ($resultObj | ConvertTo-Json -Compress -Depth 5)",
    "      Invoke-RestMethod -Method Post -Uri ($Platform + '/api/fom/agent/job-result') -ContentType 'application/json; charset=utf-8' -Body $result -TimeoutSec 120 | Out-Null",
    "    } catch {",
    "      $msg = [string]$_.Exception.Message",
    "      $fail = (@{ token = $Token; jobId = $job.id; ok = $false; message = $msg } | ConvertTo-Json -Compress)",
    "      try { Invoke-RestMethod -Method Post -Uri ($Platform + '/api/fom/agent/job-result') -ContentType 'application/json; charset=utf-8' -Body $fail -TimeoutSec 30 | Out-Null } catch {}",
    "    }",
    "  }",
    "  return 0",
    "}",
    "",
    "Write-Host ('PHARMXS FOM agent ishlayapti (port ' + $Port + ')') -ForegroundColor Green",
    "while ($true) {",
    "  try {",
    "    if (((Get-Date) - $lastHello).TotalSeconds -ge 60) { Send-Hello; $lastHello = Get-Date }",
    "  } catch {}",
    "  $sleep = 2",
    "  try { $sleep = Invoke-JobPoll } catch { $sleep = 3 }",
    "  if ($sleep -lt 1) { $sleep = 1 }",
    "  Start-Sleep -Seconds $sleep",
    "}",
  ].join("\n");
}

export function fomAgentInstallScriptTemplate(): string {
  // Placeholders inside worker too; replaced together with install script.
  const workerB64 = Buffer.from(workerScriptSource(), "utf8").toString("base64");

  return [
    "# PHARMXS FOM agent - Admin PowerShell",
    "# Firewall ochadi, lokal REPORT dan oqiydi, platformaga uzatadi.",
    "",
    "$ErrorActionPreference = 'Stop'",
    "$Platform = '__PLATFORM__'",
    "$Token = '__TOKEN__'",
    "$PreferredPort = __PORT__",
    "$TaskName = 'PHARMXS-FOM-Agent'",
    "$InstallDir = Join-Path $env:ProgramData 'PHARMXS'",
    "$WorkerPath = Join-Path $InstallDir 'fom-agent-worker.ps1'",
    "$WorkerB64 = '" + workerB64 + "'",
    "",
    "function Write-Ok([string]$m){ Write-Host ('[OK] ' + $m) -ForegroundColor Green }",
    "function Write-Warn([string]$m){ Write-Host ('[!] ' + $m) -ForegroundColor Yellow }",
    "function Write-Err([string]$m){ Write-Host ('[X] ' + $m) -ForegroundColor Red }",
    "",
    "$isAdmin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)",
    "if (-not $isAdmin) {",
    "  Write-Err 'Admin PowerShell oching (Run as administrator), keyin qayta ishga tushiring.'",
    "  exit 1",
    "}",
    "",
    "Write-Host ''",
    "Write-Host '=== PHARMXS FOM ulanishi ===' -ForegroundColor Cyan",
    "Write-Host ('Platforma: ' + $Platform)",
    "Write-Host ('Kompyuter: ' + $env:COMPUTERNAME)",
    "Write-Host ''",
    "",
    "$listenPorts = @()",
    "try {",
    "  $listenPorts = @(Get-NetTCPConnection -State Listen -ErrorAction SilentlyContinue |",
    "    Where-Object { $_.LocalPort -ge 1024 -and $_.LocalPort -le 65535 } |",
    "    Select-Object -ExpandProperty LocalPort -Unique)",
    "} catch {}",
    "",
    "$port = $PreferredPort",
    "if ($listenPorts -contains $PreferredPort) {",
    "  Write-Ok ('REPORT port tinglanmoqda: ' + $PreferredPort)",
    "} elseif ($listenPorts.Count -gt 0) {",
    "  foreach ($cand in (@(8084,8080,8085,8090,80,443) + $listenPorts)) {",
    "    if ($listenPorts -contains $cand) { $port = $cand; break }",
    "  }",
    "  Write-Warn ('Preferred port ' + $PreferredPort + ' topilmadi. Ishlatiladi: ' + $port)",
    "} else {",
    "  Write-Warn ('LISTEN port topilmadi. Firewall ' + $PreferredPort + ' uchun ochiladi.')",
    "  $port = $PreferredPort",
    "}",
    "",
    "$ruleName = ('PHARMXS FOM REPORT TCP ' + $port)",
    "Get-NetFirewallRule -DisplayName $ruleName -ErrorAction SilentlyContinue | Remove-NetFirewallRule -ErrorAction SilentlyContinue",
    "New-NetFirewallRule -DisplayName $ruleName -Direction Inbound -Action Allow -Protocol TCP -LocalPort $port -Profile Any | Out-Null",
    "Write-Ok ('Firewall ochildi (TCP ' + $port + ')')",
    "",
    "$localIps = @()",
    "try {",
    "  $localIps = @(Get-NetIPAddress -AddressFamily IPv4 -ErrorAction SilentlyContinue |",
    "    Where-Object { $_.IPAddress -notlike '127.*' -and $_.PrefixOrigin -ne 'WellKnown' } |",
    "    Select-Object -ExpandProperty IPAddress -Unique)",
    "} catch {}",
    "$publicIp = $null",
    "try { $publicIp = (Invoke-RestMethod -Uri 'https://api.ipify.org?format=json' -TimeoutSec 12).ip } catch {}",
    "if (-not $publicIp -and $localIps.Count -gt 0) { $publicIp = $localIps[0] }",
    "if ($publicIp) { Write-Host ('Ochiq IP: ' + $publicIp) }",
    "if ($localIps.Count -gt 0) { Write-Host ('Mahalliy IP: ' + ($localIps -join ', ')) }",
    "",
    "$reportListening = $listenPorts -contains $port",
    "New-Item -ItemType Directory -Force -Path $InstallDir | Out-Null",
    "",
    "$workerText = [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($WorkerB64))",
    "$workerText = $workerText.Replace('__PLATFORM__', $Platform).Replace('__TOKEN__', $Token).Replace('__PORT__', [string]$port)",
    "$utf8 = New-Object System.Text.UTF8Encoding $false",
    "[IO.File]::WriteAllText($WorkerPath, $workerText, $utf8)",
    "Write-Ok ('Worker yozildi: ' + $WorkerPath)",
    "",
    "Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false -ErrorAction SilentlyContinue",
    "$arg = '-NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File \"' + $WorkerPath + '\"'",
    "$action = New-ScheduledTaskAction -Execute 'powershell.exe' -Argument $arg",
    "$triggerStart = New-ScheduledTaskTrigger -AtStartup",
    "$triggerRepeat = New-ScheduledTaskTrigger -Once -At (Get-Date).AddMinutes(1) -RepetitionInterval (New-TimeSpan -Minutes 5) -RepetitionDuration (New-TimeSpan -Days 3650)",
    "$principal = New-ScheduledTaskPrincipal -UserId 'SYSTEM' -LogonType ServiceAccount -RunLevel Highest",
    "$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable -MultipleInstances IgnoreNew -ExecutionTimeLimit ([TimeSpan]::Zero)",
    "Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger @($triggerStart, $triggerRepeat) -Principal $principal -Settings $settings | Out-Null",
    "Start-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue",
    "Start-Process -FilePath 'powershell.exe' -ArgumentList $arg -WindowStyle Hidden",
    "Write-Ok ('Agent ishga tushdi: ' + $TaskName)",
    "Start-Sleep -Seconds 3",
    "",
    "$bodyObj = @{",
    "  token = $Token",
    "  host = $publicIp",
    "  port = $port",
    "  machine = $env:COMPUTERNAME",
    "  localIps = $localIps",
    "  reportListening = [bool]$reportListening",
    "  protocol = 'http'",
    "}",
    "$body = ($bodyObj | ConvertTo-Json -Compress)",
    "Write-Host 'Platformaga ulanilmoqda...' -ForegroundColor Cyan",
    "try {",
    "  $res = Invoke-RestMethod -Method Post -Uri ($Platform + '/api/fom/agent/hello') -ContentType 'application/json; charset=utf-8' -Body $body -TimeoutSec 60",
    "} catch {",
    "  Write-Err ('Ulanish muvaffaqiyatsiz: ' + $_.Exception.Message)",
    "  exit 1",
    "}",
    "if ($res.ok) { Write-Ok ([string]$res.message) } else { Write-Err ([string]$res.message); exit 1 }",
    "if ($null -ne $res.testOk) {",
    "  if ($res.testOk) { Write-Ok ('FOM holat: ' + $res.testMessage) } else { Write-Warn ('FOM holat: ' + $res.testMessage) }",
    "}",
    "if ($res.mode) { Write-Host ('Rejim: ' + $res.mode) }",
    "if ($res.syncStarted) { Write-Ok 'Sinxronlash platformada boshlandi.' }",
    "",
    "Write-Host ''",
    "Write-Host 'Tayyor. Kompyuterdagi FOM malumoti platformaga uzatiladi.' -ForegroundColor Green",
    "Write-Host 'Sozlamalar -> FOM da holatni kuzating, keyin toliq tortishni bosing.' -ForegroundColor Green",
    "Write-Host ''",
  ].join("\n");
}
